// Build: bundle client → embed assets into src/worker/assets.gen.ts → bundle dist/worker.js → copy schema.
import { mkdir, readdir, rm } from 'node:fs/promises';
import { join, relative } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const PUB = join(ROOT, 'src/client/public');
const DIST = join(ROOT, 'dist');

const hash = (s: string | Uint8Array) => new Bun.CryptoHasher('sha256').update(s).digest('hex').slice(0, 10);

async function bundleClient(entry: string): Promise<string> {
  const r = await Bun.build({
    entrypoints: [join(ROOT, entry)],
    target: 'browser',
    format: 'esm',
    minify: true,
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  if (!r.success) throw new AggregateError(r.logs, 'client build failed: ' + entry);
  return await r.outputs[0].text();
}

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

const TYPES: Record<string, string> = {
  html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8',
  webmanifest: 'application/manifest+json', png: 'image/png', svg: 'image/svg+xml', json: 'application/json',
};

type Asset = { type: string; body: string; b64?: boolean; immutable?: boolean };

export async function build() {
  const started = performance.now();
  const adminJs = await bundleClient('src/client/admin/main.tsx');
  const quoteJs = await bundleClient('src/client/quote/main.tsx');
  const customerJs = await bundleClient('src/client/customer/main.tsx');
  const css = await Bun.file(join(PUB, 'styles.css')).text();

  const adminPath = `/assets/admin.${hash(adminJs)}.js`;
  const quotePath = `/assets/quote.${hash(quoteJs)}.js`;
  const customerPath = `/assets/customer.${hash(customerJs)}.js`;
  const cssPath = `/assets/styles.${hash(css)}.css`;
  const version = hash(adminJs + quoteJs + customerJs + css);
  const { THEME_BOOT } = await import('../src/client/ui/theme');
  const fill = (s: string) => s.replaceAll('%THEME_BOOT%', THEME_BOOT).replaceAll('%ADMIN_JS%', adminPath).replaceAll('%QUOTE_JS%', quotePath).replaceAll('%CUSTOMER_JS%', customerPath)
    .replaceAll('%CSS%', cssPath).replaceAll('%VERSION%', version);

  const assets: Record<string, Asset> = {
    [adminPath]: { type: TYPES.js, body: adminJs, immutable: true },
    [quotePath]: { type: TYPES.js, body: quoteJs, immutable: true },
    [customerPath]: { type: TYPES.js, body: customerJs, immutable: true },
    [cssPath]: { type: TYPES.css, body: css, immutable: true },
  };
  for (const file of await walk(PUB)) {
    const rel = '/' + relative(PUB, file).replaceAll('\\', '/');
    if (rel === '/styles.css') continue;
    const ext = rel.split('.').pop()!;
    const type = TYPES[ext] ?? 'application/octet-stream';
    if (type.startsWith('image/png')) {
      assets[rel] = { type, body: Buffer.from(await Bun.file(file).arrayBuffer()).toString('base64'), b64: true };
    } else {
      assets[rel] = { type, body: fill(await Bun.file(file).text()) };
    }
  }

  const gen = `// GENERATED by scripts/build.ts — do not edit.\nexport type Asset = { type: string; body: string; b64?: boolean; immutable?: boolean };\nexport const ASSETS: Record<string, Asset> = ${JSON.stringify(assets)};\n`;
  await Bun.write(join(ROOT, 'src/worker/assets.gen.ts'), gen);

  await rm(DIST, { recursive: true, force: true });
  await mkdir(DIST, { recursive: true });
  const w = await Bun.build({
    entrypoints: [join(ROOT, 'src/worker/index.ts')],
    target: 'browser',
    format: 'esm',
    minify: true,
    outdir: DIST,
    naming: 'worker.js',
  });
  if (!w.success) throw new AggregateError(w.logs, 'worker build failed');
  await Bun.write(join(DIST, 'schema.sql'), Bun.file(join(ROOT, 'schema/schema.sql')));

  const worker = await Bun.file(join(DIST, 'worker.js')).arrayBuffer();
  const gz = Bun.gzipSync(new Uint8Array(worker)).byteLength;
  console.log(`built dist/worker.js ${(worker.byteLength / 1024).toFixed(0)} KB (gzip ${(gz / 1024).toFixed(0)} KB) in ${(performance.now() - started).toFixed(0)} ms`);
  return { gzipBytes: gz };
}

if (import.meta.main) await build();
